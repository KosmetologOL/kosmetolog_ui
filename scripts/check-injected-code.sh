#!/bin/sh
#
# Пошук коду, впровадженого у файли, які виконуються під час збірки.
#
# Техніка, від якої це захищає: у кінець останнього рядка робочого файлу
# (vite.config.ts, postcss/tailwind config, eslint.config.js, *.mjs, scripts/*)
# дописується корисне навантаження після сотні пробілів. У редакторі його не видно
# за краєм екрана, tsc його пропускає (це валідний JavaScript), а виконується воно
# у тому самому Node-процесі, де process.env уже заповнений — локально з .env*,
# на CI змінними того середовища. Один рядок бачить усі ключі збірки.
#
# ЧОМУ ЦЕ SHELL, А НЕ TS/JS.
# Гард, написаний мовою, яку він сканує, потрапляє у власний список файлів і
# знаходить сам себе: приклад виклику у коментарі чи в тексті помилки — це
# повноцінний збіг, і перевірка червоніє на чистому дереві рівно тієї секунди,
# коли файл додали в індекс. Тут pathspec обмежений розширеннями джерел
# (.ts/.tsx/.js/.jsx/.mjs/.cjs), а цей файл має розширення .sh, workflow — .yml,
# хук — без розширення. Жоден із трьох не потрапляє у власну вибірку.
# Якщо колись додаватимеш .sh у pathspec — спершу перевір, що патерни нижче
# не ловлять самі себе.
#
# Використання:  sh scripts/check-injected-code.sh
# Код виходу:    0 — чисто, 1 — є знахідки (файл і номер рядка у виводі).
#
# Портативність: POSIX sh + grep -E + awk. Без `tac` і без `grep -P` —
# ані того, ані іншого немає на macOS.

set -u

cd "$(git rev-parse --show-toplevel)" || exit 2

# Шаблон обовʼязковий: BSD-версія mktemp на macOS без нього завершується помилкою,
# на відміну від GNU-версії, де голий `mktemp` працює.
LIST=$(mktemp "${TMPDIR:-/tmp}/injguard.XXXXXX") || exit 2
# Прибрати тимчасовий файл за будь-якого виходу, зокрема Ctrl-C.
trap 'rm -f "$LIST"' EXIT HUP INT TERM

# Скануємо лише відстежувані джерела JS-родини. Згенеровані та мініфіковані
# файли виключені: довгий рядок там — норма, а не сигнал. (*.min.css у вибірку
# і так не потрапляє — css немає серед розширень, що включаються.)
git ls-files -z -- \
  '*.ts' '*.tsx' '*.js' '*.jsx' '*.mjs' '*.cjs' \
  ':(exclude)*.min.js' \
  ':(exclude)*.d.ts' > "$LIST" || exit 2

FAILED=0

# Друкує заголовок перевірки та її знахідки; порожній вивід = перевірка пройдена.
# Рішення приймається за наявністю виводу, а не за кодом виходу: grep повертає 1,
# коли збігів немає, а xargs перетворює це на 123 — покладатися на статус не можна.
report() {
  _title=$1
  _found=$2
  if [ -n "$_found" ]; then
    FAILED=1
    echo "ЗНАЙДЕНО: $_title"
    echo "$_found" | sed 's/^/  /' | cut -c 1-200
    echo
  fi
}

# 1. Аномально довгий рядок — основна ознака дописаного навантаження.
found=$(xargs -0 awk '
  length($0) > 2000 {
    printf "%s:%d: рядок довжиною %d символів\n", FILENAME, FNR, length($0)
  }' < "$LIST" 2>/dev/null || true)
report "рядок довший за 2000 символів" "$found"

# 2. Виконання розкодованого рядка: eval/Function над atob, Buffer.from,
#    decodeURIComponent, fromCharCode. Найсильніший окремий сигнал.
found=$(xargs -0 grep -nHE \
  '(eval|Function)[[:space:]]*\(.*(atob|Buffer[[:space:]]*\.[[:space:]]*from|decodeURIComponent|fromCharCode)' \
  < "$LIST" 2>/dev/null || true)
report "виконання розкодованого рядка (eval/Function над декодером)" "$found"

# 3. createRequire в ESM-контексті — типовий спосіб дотягнутися до child_process
#    там, де require недоступний.
found=$(xargs -0 grep -nHE 'createRequire[[:space:]]*\(' < "$LIST" 2>/dev/null || true)
report "createRequire у джерелах" "$found"

# 4. Динамічне виконання коду в будь-якому вигляді.
found=$(xargs -0 grep -nHE \
  '(^|[^A-Za-z0-9_$.])eval[[:space:]]*\(|new[[:space:]]+Function[[:space:]]*\(|(^|[^A-Za-z0-9_$.])Function[[:space:]]*\(' \
  < "$LIST" 2>/dev/null || true)
report "динамічне виконання коду (eval / конструктор Function)" "$found"

# 5. «Полиця» з пробілів посеред рядка: код, багато пробілів, знову код.
#    Ловить саме описану техніку навіть тоді, коли навантаження коротше за 2000
#    символів. Відступ на початку рядка сюди не потрапляє — перед пробілами
#    обовʼязково має бути непробільний символ.
found=$(xargs -0 grep -nHE '[^[:space:]][[:space:]]{40,}[^[:space:]]' < "$LIST" 2>/dev/null || true)
report "код після довгого блоку пробілів усередині рядка" "$found"

if [ "$FAILED" -eq 0 ]; then
  echo "Перевірка на впроваджений код: чисто (просканованих файлів: $(tr '\0' '\n' < "$LIST" | grep -c .))."
  exit 0
fi

cat <<'MSG'
Перевірка на впроваджений код НЕ ПРОЙДЕНА.

Якщо ці рядки написані не тобою — вважай ключі середовища скомпрометованими.
Що робити: docs/injected-code-guard.md
MSG
exit 1
