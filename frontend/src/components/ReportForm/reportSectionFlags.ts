// Прапорці розділів рекомендаційного листа — єдине місце, де вмикається
// й вимикається розділ одразу в усіх форматах експорту.
//
// «Засоби»: клієнт попросив тимчасово не включати розділ до листа — рішення
// перенесене сюди з коментаря в html/generateReportHtml.ts; точні дата й хто
// підтвердив у репозиторії не зафіксовані, а окремого підтвердження щодо
// .docx-картки під час C7 отримати не вдалося. Тому діє домовленість тікета
// за замовчуванням: один прапорець керує ОБОМА форматами — HTML-листом для
// пацієнта і дописом у .docx-картку (раніше DOCX друкував «Засоби»
// безумовно, і документи розходилися за змістом). Разом із самим розділом
// прапорець вимикає й нотатку «Важливо» до засобів.
//
// Якщо клієнт підтвердить, що в картці розділ усе-таки потрібен — розділити
// на INCLUDE_MEDICATIONS_SECTION_HTML і INCLUDE_MEDICATIONS_SECTION_DOCX тут
// же, у цьому файлі: рішення має лишатися в одному місці.
//
// Увага: PDF-експорт (pdf/ReportPdfDocument.tsx) розділу «Засоби» не має
// зовсім — засоби туди навіть не передаються параметрами, тож перемикання
// цього прапорця на PDF не впливає.
export const INCLUDE_MEDICATIONS_SECTION: boolean = false;
