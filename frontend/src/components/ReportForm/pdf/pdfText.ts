// Підготовка рядка до набору шрифтом Noah.
//
// Noah — фірмовий шрифт без емодзі та інших піктограм. У браузері такий
// символ підхоплює системний резервний шрифт, а @react-pdf резервних
// шрифтів не має: відсутній гліф він бере за індексом 0 і друкує сміття
// (📞 у нотатці лікаря виходило як «=Þ»). Прибрати символ чесніше, ніж
// показати пацієнтові кракозябру, тому піктограми вирізаємо разом із
// модифікаторами тону шкіри, селекторами варіантів (U+FE0E/U+FE0F) та
// зʼєднувачем (U+200D), які без них лишаються висіти в рядку.
//
// Зібрано через RegExp з рядка, а не літералом: комбінувальні знаки в
// літералі невидимі очима й гинуть при першому ж копіюванні файлу, а в
// одному символьному класі поруч зі звичайними на них ще й справедливо
// свариться ESLint (no-misleading-character-class).
const UNSUPPORTED = new RegExp(
  ["\\p{Extended_Pictographic}", "[\\u{1F3FB}-\\u{1F3FF}]", "\\uFE0E", "\\uFE0F", "\\u200D"].join(
    "|",
  ),
  "gu",
);

/** Прибирає гліфи, яких немає в Noah, і схлопує пробіли, що лишились. */
export const pdfText = (text: string): string =>
  text.replace(UNSUPPORTED, "").replace(/[ \t]{2,}/g, " ");
