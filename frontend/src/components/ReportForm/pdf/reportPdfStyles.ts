/** Той самий --lh, що й у друкованому CSS. */
export const LINE_HEIGHT_RATIO = 1.32;

/**
 * Висота рядка в пунктах для заданого кегля.
 *
 * Повертає РЯДОК з одиницями, і це принципово. Число в `lineHeight`
 * @react-pdf множить на `fontSize` із того самого обʼєкта стилів, а якщо
 * `fontSize` там немає — на власні дефолтні 18pt: успадкований кегль на
 * цьому етапі ще невідомий (див. transformLineHeight у
 * @react-pdf/stylesheet). Саме через це весь текст звіту друкувався з
 * інтерлʼяжем 1.32 × 18 ≈ 23.8pt замість 1.32 × 9 ≈ 11.9pt — рядки
 * розповзались утричі, і лист розтягувався з трьох аркушів на шість.
 * Значення з одиницями рушій бере як абсолютне, тож ця пастка зникає.
 *
 * Правило просте: разом із `lineHeight` завжди йде `lh(кегль)`, ніколи
 * голе число.
 */
export const lh = (size: number): string =>
  `${(size * LINE_HEIGHT_RATIO).toFixed(2)}pt`;

