let fontsRegistered = false;

/** Реєстрація шрифтів має статися один раз до першого рендера. */
export const registerReportFonts = (): void => {
  if (fontsRegistered) return;
  fontsRegistered = true;

  Font.register({
    family: "Noah",
    fonts: [
      { src: NoahRegularUrl, fontWeight: 400 },
      { src: NoahBoldUrl, fontWeight: 700 },
      { src: NoahItalicUrl, fontWeight: 400, fontStyle: "italic" },
      { src: NoahBoldItalicUrl, fontWeight: 700, fontStyle: "italic" },
    ],
  });

  // Типове перенесення зі складами розраховане на англійську і рве
  // українські слова навпіл у випадкових місцях. Повертаємо слово цілим —
  // хай переносить його на наступний рядок повністю.
  Font.registerHyphenationCallback((word) => [word]);
};

